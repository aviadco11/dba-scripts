
-- Get Columns Type
SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_PRECISION_RADIX, NUMERIC_SCALE
FROM INFORMATION_SCHEMA.COLUMNS 
order by DATA_TYPE, CHARACTER_MAXIMUM_LENGTH desc


-- Get PK field name and Type used
SELECT a.TABLE_CATALOG, a.TABLE_SCHEMA,a.TABLE_NAME, b.CONSTRAINT_NAME,a.COLUMN_NAME, a.DATA_TYPE, a.CHARACTER_MAXIMUM_LENGTH
from INFORMATION_SCHEMA.KEY_COLUMN_USAGE b
join INFORMATION_SCHEMA.COLUMNS a
on a.TABLE_NAME = b.TABLE_NAME and a.COLUMN_NAME = b.COLUMN_NAME
WHERE OBJECTPROPERTY(OBJECT_ID(CONSTRAINT_SCHEMA + '.' + QUOTENAME(CONSTRAINT_NAME)), 'IsPrimaryKey') = 1
and a.DATA_TYPE like '%varchar%' and a.TABLE_SCHEMA not like 'sysPartition'
order by a.CHARACTER_MAXIMUM_LENGTH desc

